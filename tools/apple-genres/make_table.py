"""Writes crates/octo-core/src/charts/apple_genre_names.rs from Apple's US genre list.

Every genre id under Music (all depths) with its English name. Fails when a name has a letter
outside Latin script.
"""

import datetime
import json
import pathlib
import sys
import unicodedata
import urllib.request

URL = "https://itunes.apple.com/WebObjects/MZStoreServices.woa/ws/genres?id=34&cc=us"
OUT = (
    pathlib.Path(__file__).resolve().parents[2]
    / "crates/octo-core/src/charts/apple_genre_names.rs"
)


def is_latin(name):
    for ch in name:
        if ch.isalpha() and not unicodedata.name(ch, "").startswith("LATIN"):
            return False
    return True


def walk(node, out):
    for entry in node.values():
        out.append((entry["id"], entry["name"]))
        walk(entry.get("subgenres") or {}, out)


def main():
    with urllib.request.urlopen(URL, timeout=30) as response:
        data = json.load(response)
    pairs = []
    walk(data, pairs)
    bad = [(i, n) for i, n in pairs if not is_latin(n)]
    if bad:
        sys.exit("Genre names outside Latin script: " + ", ".join(f"{i} {n!r}" for i, n in bad))
    unique = {}
    for genre_id, name in pairs:
        unique[genre_id] = name
    rows = sorted(unique.items(), key=lambda p: int(p[0]))
    today = datetime.date.today().isoformat()
    lines = [
        f"//! Apple's English genre names for every id under Music, read from {URL}",
        f"//! on {today}. Generated by tools/apple-genres/make_table.py; do not edit by hand.",
        "",
        "pub const APPLE_GENRE_NAMES: &[(&str, &str)] = &[",
    ]
    for genre_id, name in rows:
        escaped = name.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    ("{genre_id}", "{escaped}"),')
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {len(rows)} genres to {OUT}")


if __name__ == "__main__":
    main()
